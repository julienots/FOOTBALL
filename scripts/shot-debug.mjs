import { getWorld } from '../src/data/world.js';
import { FootballMatch } from '../src/football/engine.js';
const w = getWorld();
const m = new FootballMatch({ home: w.clubs[2], away: w.clubs[7], seed: 'g2', speed: 1, h2Offset: 3840, record: false, keepEvents: true });
m.syncTo(2700);
const ev = m.events; const prev = {}; const hist = {};
ev.forEach((e, j) => { if (e.type === 'shot') { const p = ev[j - 1]; const k = p.type + (p.rtype || ''); prev[k] = (prev[k] || 0) + 1; const b = Math.floor(e.dist / 5) * 5; hist[b] = (hist[b] || 0) + 1; } });
console.log(prev, hist);
let c = 0;
ev.forEach((e, j) => { if (e.type === 'shot' && c++ < 6) console.log(ev.slice(j - 3, j + 3).map(x => `${(x.tick * .05).toFixed(1)} ${x.type} ${x.name || x.fromName || ''} ${x.dist || ''} ${x.caught ?? ''}`).join(' | ')); });
